let current: Lang = 'en';

export const getLang = (): Lang => current;
export const setCurrentLang = (l: Lang): void => {
  current = l;
};

export function hasKey(k: string): k is Key {
  return Object.prototype.hasOwnProperty.call(en, k);
}

export function translateWith(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  const text = (lang === 'zh' ? zh[key] : en[key]) ?? en[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (_m, name: string) => String(vars[name] ?? `{${name}}`)) : text;
}

// Translate in whatever language the UI is currently showing (for non-React code).
export const tr = (key: Key, vars?: Record<string, string | number>): string =>
  translateWith(current, key, vars);
